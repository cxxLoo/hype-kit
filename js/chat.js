  function norm(s){ return String(s||"").toLowerCase().replace(/\s+/g,""); }

  // 从数据库加载的问答（后台可编辑）；为空时回退到内置 KB
  let DB_KB = null;

  async function loadFAQs(){
    try{
      if(!window.sb) return;
      const { data, error } = await window.sb
        .from("faqs").select("keywords,answer,category,sort,enabled")
        .eq("enabled", true).order("sort", { ascending:true });
      if(error) throw error;
      if(data && data.length){
        DB_KB = data.map(r=>({
          cat: r.category || "咨询",
          kw:  String(r.keywords||"").split(/[，,\s]+/).map(s=>s.trim()).filter(Boolean),
          a:   r.answer || ""
        }));
      }
    }catch(e){
      console.warn("[chat] FAQ 加载失败，使用内置知识库：", e.message);
    }
  }

  function detectCategory(text){
    const t = norm(text);
    if(/投诉|举报|态度差|骗|差评/.test(t)) return "投诉";
    if(/建议|希望|最好能|期待|增加|改进/.test(t)) return "建议";
    if(/退|换|售后|坏|瑕疵|质量|破损/.test(t)) return "售后";
    return "咨询";
  }

