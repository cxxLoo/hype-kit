      if(!t) return { text:"您似乎没有输入内容呢～可以把想问的问题打给我哦😊", category:"咨询" };
      const list = (DB_KB && DB_KB.length) ? DB_KB : KB;
      let best = null, bestScore = 0;
      for(const item of list){
        let score = 0;
        for(const k of item.kw){ if(k && t.includes(norm(k))) score++; }
        if(score > bestScore){ bestScore = score; best = item; }
      }
      if(best && bestScore > 0) return { text: best.a, category: best.cat };
      return { text: FALLBACK, category: detectCategory(text) };
