  /* 轻量上下文：短应答（嗯 / 好的 / 然后呢）时顺着上一个话题继续 */
  const AFFIRM = /^(嗯+|哦+|噢+|啊+|好+的?|行+|可以|ok|okay|是的?|对+|然后呢?|还有呢?|继续|嗯呢)$/i;
