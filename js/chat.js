  function norm(s){ return String(s==null?"":s).toLowerCase().replace(/\s+/g,""); }
  function pick(arr){ return arr[Math.floor(Math.random()*arr.length)] || ""; }

  /* 后台知识库：与内置合并（后台优先命中，内置永远兜底，避免只配一条就丢掉全部话术） */
  let DB_KB = null;

  async function loadFAQs(){
    try{
      if(!window.sb) return;
      const { data, error } = await window.sb
        .from("faqs").select("keywords,answer,category,sort,enabled")
        .eq("enabled", true).order("sort", { ascending:true });
      if(error) throw error;
      if(data && data.length){
        DB_KB = data.map(r=>({
          cat: r.category || "咨询",
          kw:  String(r.keywords||"").split(/[，,、\s]+/).map(s=>s.trim()).filter(Boolean),
          a:   String(r.answer||"").trim()
        })).filter(x=>x.a && x.kw.length);
      }
    }catch(e){
      console.warn("[chat] FAQ 加载失败，使用内置知识库：", e && e.message);
    }
  }

  function detectCategory(text){
    const t = norm(text);
    if(/投诉|举报|态度差|骗|差评|生气/.test(t)) return "投诉";
    if(/建议|希望|最好能|期待|增加|改进/.test(t)) return "建议";
    if(/退|换|售后|坏|瑕疵|质量|破损|催/.test(t)) return "售后";
    return "咨询";
  }

  /* 加权匹配：命中的关键词越长越精准，避免「鞋」这类单字误判 */
  function match(list, t){
    let best = null, bestScore = 0;
    for(const item of list){
      if(!item || !item.kw || !item.a) continue;
      let score = 0;
      for(const k of item.kw){
        const key = norm(k);
        if(key && t.indexOf(key) >= 0) score += key.length;
      }
      if(score > bestScore){ bestScore = score; best = item; }
    }
    return bestScore > 0 ? best : null;
  }

