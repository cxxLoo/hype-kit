--  依赖：需先执行 accounts.sql（用到 public.is_admin()）
--  用法：Supabase → SQL Editor → New query → 粘贴本文件 → Run
-- =====================================================================

-- ---------- 1. FAQ 表 ----------
create table if not exists public.faqs (
  id         uuid primary key default gen_random_uuid(),
  keywords   text not null default '',        -- 触发关键词，逗号/空格分隔，命中任一即回复
  answer     text not null default '',        -- 回复内容（可多行）
  category   text not null default '咨询',      -- 咨询 / 售后 / 投诉 / 建议 / 其他
  sort       integer not null default 100,     -- 排序：越小越靠前
  enabled    boolean not null default true,    -- 是否启用
  created_at timestamptz not null default now()
);

create index if not exists faqs_sort_idx on public.faqs(sort);

-- ---------- 2. RLS：公开可读（前台客服要用），仅管理员可写 ----------
alter table public.faqs enable row level security;

drop policy if exists "public read faqs" on public.faqs;
create policy "public read faqs" on public.faqs
  for select using (true);

drop policy if exists "admin write faqs" on public.faqs;
create policy "admin write faqs" on public.faqs
  for all using (public.is_admin()) with check (public.is_admin());

